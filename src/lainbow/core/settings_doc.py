"""Render the configuration reference (docs/configuration.md) from the settings classes."""

from pydantic import SecretStr

from lainbow.core import models
from lainbow.core.settings import (
    EngineSettings,
    ServerSettings,
    SettingRow,
)

# Keys of the `.env` file read by compose.yaml: (key, default, meaning).
COMPOSE_KEYS: tuple[tuple[str, str, str], ...] = (
    (
        "MUSIC_DIR",
        "required",
        "Music folder on the host; the same folder as MPD's `music_directory`.",
    ),
    ("POSTGRES_PASSWORD", "required", "Password of the bundled database."),
    (
        "ENGINE_TOKEN",
        "required",
        "Token shared by the server and the bundled engine: `lbe_<32 hex digits>_<secret>`.",
    ),
    ("COMPOSE_PROFILES", "required", "Engine to run: `cpu`, `cuda` or `rocm`."),
    ("DATA_DIR", "`./data`", "Holds `postgres/` and `models/`."),
    ("PORT", "`8000`", "Port the API listens on."),
    ("LAINBOW_VERSION", "`2`", "Image tag to run."),
    ("GPU_GID", "`video`", "ROCm only: group that owns `/dev/kfd` and `/dev/dri`."),
    (
        "HSA_OVERRIDE_GFX_VERSION",
        "unset",
        "ROCm only: for GPUs that ROCm does not officially support, for example `11.0.0`.",
    ),
)

# Shown instead of the placeholder value used to build the default instance.
_PLACEHOLDER_DB_URL = "postgresql+psycopg://placeholder"
_SPECIAL_DEFAULTS = {"LAINBOW_DATABASE_URL": "set by compose"}

_METHOD_TEXT = """\
Each model has its own analysis method, set by two variables per model:

- `LAINBOW_<MODEL>_MAX_SEC`: seconds from the start of a track to analyze (`0` = the whole track).
- `LAINBOW_<MODEL>_DROP_TAIL`: `true` drops the last min(30 s, 15%) of tracks of 60 s or longer.

`<MODEL>` is the upper-case model name, for example `MUQ_MULAN`.

Every vector is stored with a profile, a label built from the model revision and the method, such as
`r1-max180-keeptail`. Changing a method creates a new profile, so the library is analyzed again for
that model. Vectors of the previous method are kept, so changing back is free.
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{text}`" if text else ""


def _table(header: tuple[str, str, str], rows: list[tuple[str, str, str]]) -> str:
    lines = [
        f"| {header[0]} | {header[1]} | {header[2]} |",
        "| --- | --- | --- |",
    ]
    lines.extend(f"| {_cell(a)} | {_cell(b)} | {_cell(c)} |" for a, b, c in rows)
    return "\n".join(lines)


def _rows(rows: list[SettingRow]) -> list[tuple[str, str, str]]:
    result: list[tuple[str, str, str]] = []
    for row in rows:
        default = _SPECIAL_DEFAULTS.get(row.env_var)
        if default is None:
            default = "unset" if row.value == "None" else _code(row.value)
        result.append((_code(row.env_var), default, row.description))
    return result


def render_markdown() -> str:
    """Return the full text of docs/configuration.md."""
    server = ServerSettings.model_construct(
        database_url=SecretStr(_PLACEHOLDER_DB_URL),
        music_dir=ServerSettings.model_fields["music_dir"].default,
        host=ServerSettings.model_fields["host"].default,
        port=ServerSettings.model_fields["port"].default,
        scan_interval_min=ServerSettings.model_fields["scan_interval_min"].default,
        local_engine_token=None,
        lease_sec=ServerSettings.model_fields["lease_sec"].default,
        text_engine_url=ServerSettings.model_fields["text_engine_url"].default,
        models=list(ServerSettings.model_fields["models"].default),
        methods={str(k): spec.default_method for k, spec in models.MODELS.items()},
        explicit_method_vars=frozenset(),
        log_level="info",
    )
    engine = EngineSettings.model_construct(
        server_url=None,
        token=None,
        accel=EngineSettings.model_fields["accel"].default,
        models_dir=EngineSettings.model_fields["models_dir"].default,
        music_dir=None,
        claim_size=EngineSettings.model_fields["claim_size"].default,
        decoders=EngineSettings.model_fields["decoders"].default,
        text_port=EngineSettings.model_fields["text_port"].default,
        idle_sec=EngineSettings.model_fields["idle_sec"].default,
        log_level="info",
    )
    # server_url and token have no default; document them as required.
    engine_rows = [
        (_code(r.env_var), "required", r.description)
        if r.env_var in ("LAINBOW_SERVER_URL", "LAINBOW_TOKEN")
        else row
        for r, row in zip(engine.setting_rows(), _rows(engine.setting_rows()), strict=True)
    ]

    method_defaults = ", ".join(
        f"{spec.short_name} {spec.default_method.max_sec} s" for spec in models.MODELS.values()
    )
    parts = [
        "<!-- Generated by scripts/gen-docs.sh from the settings classes. Do not edit by hand. -->",
        "# Configuration",
        "## Where things are (compose, `.env`)",
        "Compose reads these keys from the `.env` file next to `compose.yaml`. "
        "`./lainbow init` writes the required ones.",
        _table(
            ("Key", "Default", "Meaning"),
            [(_code(k), d, m) for k, d, m in COMPOSE_KEYS],
        ),
        "## Server settings (`LAINBOW_*`)",
        "Optional. Put them in `.env`; the server reads every `LAINBOW_*` variable. "
        "`./lainbow config` shows the effective values.",
        _table(("Variable", "Default", "Meaning"), _rows(server.setting_rows())),
        "## Analysis methods",
        _METHOD_TEXT.rstrip("\n"),
        f"Default `MAX_SEC` per model: {method_defaults}.",
        "## Engine settings",
        "Used by the engine, for example on a GPU machine. In compose, the bundled engine gets "
        "its server URL, token and folders from `compose.yaml`.",
        _table(("Variable", "Default", "Meaning"), engine_rows),
    ]
    return "\n\n".join(parts) + "\n"


if __name__ == "__main__":
    print(render_markdown(), end="")
